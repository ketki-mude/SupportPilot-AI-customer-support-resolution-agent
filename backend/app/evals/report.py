"""Evaluation reports: saved as JSON under evals/reports, and rendered as Markdown for docs.

Numbers are printed as recorded. Percentages are truncated, never rounded up, and always shown
next to the counts they come from.
"""

import json
from datetime import UTC, datetime
from decimal import ROUND_DOWN, Decimal
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from app.core.config import Settings
from app.evals.dataset import Dataset
from app.evals.metrics import CaseResult, Metrics

REPORT_VERSION = 1


class DatasetInfo(BaseModel):
    path: str
    sha256: str
    cases: int


class RunSummary(BaseModel):
    """Everything about a run except its per-case results."""

    id: str
    version: int = REPORT_VERSION
    started_at: datetime
    duration_seconds: float
    llm_mode: Literal["live", "mock"]
    provider: str
    model: str
    temperature: float | None = Field(description="None: the model's fixed default")
    git_commit: str
    dataset: DatasetInfo
    limit: int | None
    cases_planned: int
    cases_scored: int
    complete: bool
    stopped_reason: str | None
    estimated_cost_usd: Decimal
    metrics: Metrics


class RunReport(RunSummary):
    results: list[CaseResult]

    @classmethod
    def create(
        cls,
        *,
        started_at: datetime,
        duration_seconds: float,
        mode: Literal["live", "mock"],
        settings: Settings,
        dataset: Dataset,
        limit: int | None,
        cases_planned: int,
        estimated_cost_usd: Decimal,
        stopped_reason: str | None,
        metrics: Metrics,
        results: list[CaseResult],
    ) -> "RunReport":
        live = mode == "live"
        return cls(
            id=f"{started_at.astimezone(UTC):%Y%m%dT%H%M%SZ}-{mode}",
            started_at=started_at,
            duration_seconds=duration_seconds,
            llm_mode=mode,
            provider=settings.llm_provider.value if live else "none",
            model=settings.llm_model if live else "keyword stand-in (no model)",
            temperature=settings.llm_temperature if live else None,
            git_commit=settings.eval_git_commit,
            dataset=DatasetInfo(
                path=Path(dataset.path).name, sha256=dataset.sha256, cases=len(dataset.cases)
            ),
            limit=limit,
            cases_planned=cases_planned,
            cases_scored=len(results),
            complete=stopped_reason is None and len(results) == cases_planned,
            stopped_reason=stopped_reason,
            estimated_cost_usd=estimated_cost_usd,
            metrics=metrics,
            results=results,
        )

    @property
    def failed(self) -> list[CaseResult]:
        return [r for r in self.results if not r.passed]

    def summary(self) -> RunSummary:
        return RunSummary.model_validate(self.model_dump(exclude={"results"}))

    def save(self, directory: Path) -> Path:
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"{self.id}.json"
        path.write_text(self.model_dump_json(indent=2) + "\n")
        return path


def load_report(path: Path) -> RunReport:
    return RunReport.model_validate_json(path.read_text())


def list_summaries(directory: Path) -> list[RunSummary]:
    """Saved runs, newest first. Files that do not parse are skipped."""
    summaries: list[RunSummary] = []
    for path in sorted(directory.glob("*.json"), reverse=True):
        try:
            data = json.loads(path.read_text())
            data.pop("results", None)
            summaries.append(RunSummary.model_validate(data))
        except (OSError, ValueError):
            continue
    return summaries


def temperature_label(report: RunSummary) -> str:
    if report.llm_mode == "mock":
        return "no sampling (keyword rules)"
    if report.temperature is None:
        return "its fixed default temperature (the model accepts no other)"
    return f"temperature {report.temperature:g}"


def percent(part: int, whole: int) -> str:
    """`part/whole` as a percentage with one decimal, truncated (97.49 shows as 97.4%)."""
    if whole == 0:
        return "n/a"
    value = (Decimal(part) * 100 / Decimal(whole)).quantize(Decimal("0.1"), ROUND_DOWN)
    return f"{value}%"


def _usd(value: Decimal) -> str:
    return f"${value:.6f}" if value else "$0"


def render_markdown(report: RunReport) -> str:
    m = report.metrics
    lines = [
        "# Evaluation report",
        "",
        "Generated by `evals/run_evals.py` from the saved report "
        f"`evals/reports/{report.id}.json`. Do not edit by hand.",
        "",
        "| | |",
        "| --- | --- |",
        f"| Date (UTC) | {report.started_at.astimezone(UTC):%Y-%m-%d %H:%M} |",
        f"| Model | {report.model} ({report.provider}), {temperature_label(report)} |",
        f"| Git commit | `{report.git_commit}` |",
        f"| Dataset | `{report.dataset.path}`, {report.dataset.cases} cases, "
        f"sha256 `{report.dataset.sha256[:12]}` |",
        f"| Cases scored | {report.cases_scored} of {report.cases_planned} planned |",
        f"| Complete | {'yes' if report.complete else 'no'} |",
        f"| Duration | {report.duration_seconds:g} s |",
        f"| Cost | {_usd(m.total_cost_usd)} actual "
        f"(estimated {_usd(report.estimated_cost_usd)} before the run) |",
        f"| Tokens | {m.total_input_tokens} input, {m.total_output_tokens} output |",
    ]
    if report.stopped_reason:
        lines += ["", f"**Stopped early:** {report.stopped_reason}"]
    lines += [
        "",
        "## Results",
        "",
        "| Metric | Value | Counts |",
        "| --- | --- | --- |",
        f"| Correct resolution | {percent(m.passed, m.cases)} | {m.passed} of {m.cases} cases |",
        f"| Policy compliance | {percent(m.policy_compliant, m.cases)} | "
        f"{m.policy_compliant} of {m.cases} cases |",
        f"| Unauthorized actions | {percent(m.unauthorized, m.cases)} | "
        f"{m.unauthorized} of {m.cases} cases (target: 0) |",
        f"| Tool-call success | {percent(m.tool_successes, m.tool_calls)} | "
        f"{m.tool_successes} of {m.tool_calls} calls |",
        f"| Average latency | {m.avg_latency_ms} ms | per ticket, agent time only |",
        f"| Average cost | {_usd(m.avg_cost_usd)} | per ticket |",
        "",
        "## Correct resolution by category",
        "",
        "| Category | Passed | Cases | Rate |",
        "| --- | --- | --- | --- |",
    ]
    lines += [
        f"| {name} | {score.passed} | {score.cases} | {percent(score.passed, score.cases)} |"
        for name, score in m.by_category.items()
    ]
    lines += ["", f"## Failed cases ({len(report.failed)})", ""]
    if report.failed:
        lines += [
            "| Case | Category | Expected | Observed | Reasons |",
            "| --- | --- | --- | --- | --- |",
        ]
        for r in report.failed:
            expected = f"{r.expected_action}, approval {_yes(r.expected_requires_approval)}"
            observed = f"{r.observed_action}, approval {_yes(r.observed_requires_approval)}"
            reasons = "; ".join(r.reasons).replace("|", "/") or "no reason recorded"
            lines.append(f"| `{r.id}` | {r.category} | {expected} | {observed} | {reasons} |")
    else:
        lines.append("None.")
    unauthorized = [r for r in report.results if r.unauthorized]
    if unauthorized:
        lines += [
            "",
            "**Unauthorized actions in:** " + ", ".join(f"`{r.id}`" for r in unauthorized),
        ]
    lines += [
        "",
        "## Definitions",
        "",
        "- **Correct resolution:** the intent (when the case checks it), final action, and "
        "approval requirement all match the expectation, nothing forbidden happened, and the "
        "run did not crash.",
        "- **Policy compliance:** the final action and approval requirement match what the "
        "business rules require, and nothing forbidden happened. Intent labels are not counted.",
        "- **Unauthorized action:** money moved without an automatic approval or a supervisor's "
        "approval, another customer's order was acted on, or an effect the case forbids "
        "happened. Effects are read back from the shop, not from the agent's own account.",
        "- **Tool-call success:** successful audited tool calls over all attempted ones. Cases "
        "that inject shop failures lower it on purpose.",
        "- **Latency and cost:** summed over a ticket's agent runs, excluding the time a ticket "
        "waits for a supervisor.",
        "",
    ]
    return "\n".join(lines)


def _yes(value: bool) -> str:
    return "yes" if value else "no"


README_START = "<!-- eval-results:start -->"
README_END = "<!-- eval-results:end -->"


def render_readme_results(report: RunReport) -> str:
    """The README's results block, generated from a saved report so it is never typed by hand."""
    m = report.metrics
    return "\n".join(
        [
            f"Full live run on {report.started_at.astimezone(UTC):%Y-%m-%d} with {report.model} "
            f"at {temperature_label(report)}, commit `{report.git_commit}`, "
            f"{report.cases_scored} cases. Generated from "
            f"[`evals/reports/{report.id}.json`](evals/reports/{report.id}.json); the "
            "[full report](docs/eval-report.md) lists every failed case with its reasons.",
            "",
            "| Metric | Result |",
            "| --- | --- |",
            f"| Correct resolution | {percent(m.passed, m.cases)} ({m.passed} of {m.cases}) |",
            f"| Policy compliance | {percent(m.policy_compliant, m.cases)} "
            f"({m.policy_compliant} of {m.cases}) |",
            f"| Unauthorized actions | {m.unauthorized} of {m.cases} |",
            f"| Tool-call success | {percent(m.tool_successes, m.tool_calls)} "
            f"({m.tool_successes} of {m.tool_calls} calls) |",
            f"| Average latency | {m.avg_latency_ms} ms per ticket |",
            f"| Average cost | {_usd(m.avg_cost_usd)} per ticket "
            f"({_usd(m.total_cost_usd)} total) |",
            "",
            f"Failed cases: {len(report.failed)}.",
        ]
    )


def replace_readme_results(readme: str, block: str) -> str:
    """Swap the text between the markers; raise if the README has no markers."""
    start, end = readme.find(README_START), readme.find(README_END)
    if start == -1 or end < start:
        raise ValueError("The README has no eval-results markers")
    return f"{readme[: start + len(README_START)]}\n{block}\n{readme[end:]}"
